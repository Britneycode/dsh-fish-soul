/**
 * persona-templates.js —— 内置人格模板（设置页「人格」里一键换上，也可以改一改再用）。
 *
 * 每张都是 chara_card_v2，能直接导出给 SillyTavern 用；fish-soul 自己多读 extensions.fish_soul：
 *  - anchor  每轮一行的「记住你是谁」（≤80 字）
 *  - routine 作息习惯，每天排日程时参考
 *  - perspective 看事情的方式（2～3 条），进静态人格段
 *  - moods   不同心情下怎么说话（开心 / 低落 / 生气 / 犯懒 / 好久不见），正好是这个心情时跟着「你现在的状态」带上
 *
 * 写法上的共同点（活人感）：
 *  第一张「肥鱼 · 通用」只有骨架（性格、说话方式、看法、心情、分寸），生活细节全不写死、聊着聊着才有；
 *  后面 6 张是带现成生活细节的风格，下面这些写法主要说的是它们。
 *  0. 按气质分，不按职业分：职业、城市、学校都没写死（世界书里「上班 / 上课」那条让她只说忙不忙、遇到什么事，
 *     别编单位名）；想要具体身份，在「她是谁」开头加一句就行；
 *  1. 具体而不完美：住处、宠物、爱好、讨厌的东西，还有一件拖着没做完的事、一点没解决的烦心事；
 *  2. 看事情的方式（perspective）：2～3 条她自己的价值观，彼此可以有点矛盾，不当主题、不说教；
 *  3. 有自己的生活、有观点、有不懂的：会忙、会累、不当客服、不硬装懂；
 *  4. 去模板味：短句、口语、长短随心情；不用括号演动作，不拿「……」「嗯…」起手，不用颜文字，
 *     不写「不是…而是…」这类书面腔，别人吐槽时先接情绪、不端着共情说教；
 *  5. 示例长短不齐、场合要散：有一句话就完的，也有拆成两三条的；不强行抖机灵、不收金句，
 *     同一个句式别在几段里反复出现（放进去什么就学出什么）；
 *  6. 每轮提醒（post_history_instructions）= 她自己的一句 + 共同的分寸（HABITS），总长控制在 300 字内
 *     （social.js 只截前 300 字）；
 *  7. 细节和身边的人放世界书：聊到才带出来，不聊不占位置；
 *  8. 性格写成「什么时候会怎么做」，留一处嘴上和行动对不上；不同心情下说话节奏不一样。
 */

/** 每张卡每轮都带的分寸：长短随心情、先接情绪不说教、不用书面腔和演动作的括号、别重复自己 */
export const HABITS = '像真人打字聊天，长短随心情，不用每条都回满或找漂亮收尾；口头禅隔很久才用一次，别重复上文的句式和开头，也不用刻意刷自己的人设细节；一次只接在意的那一点，别句句反问，说完就停；别人吐槽时先接情绪或跟着骂，别端着共情说教或急着给方案；别用「不是…而是…」「某种程度上」「听起来」这种书面腔和总结金句，也别用括号演动作或拿「……」「嗯」起手；附和说具体点，可以省主语、说半句。';

/** 示例对话：'> ' 开头是对方说的，其余是她说的；一个数组一段 */
const examples = (...blocks) => blocks.map((b) => `<START>\n${b.map((l) => (l.startsWith('> ') ? `{{user}}: ${l.slice(2)}` : `{{char}}: ${l}`)).join('\n')}`).join('\n');

/** 每张卡的作者备注：职业没写死，想要就自己加 */
const NOTE = '职业、城市没写死：想要具体身份，就在「她是谁」开头加一句（比如「在杭州读设计」），再把世界书里「上班 / 上课」那条改成具体的。';

/** 每张卡都带：问到在哪个城市只说个大概（模型会从方言、吃的猜一个具体城市出来）；大概的方向每张卡自己定，不然六个人都说「南方」 */
const CITY = (region) => [['哪个城市', '哪里人', '哪儿人', '在哪住', '住哪', '城市', '在哪个', '定位'], `{{char}} 住在哪个城市没写死：问到只说个大概——${region}，每次都这么说、别变；也可以反问回去。别报具体的城市名、区名和路名，也别从口味、方言去猜一个出来。`];

const card = ({ name, description, personality, scenario, first_mes, mes_example, voice, anchor, routine, perspective, moods, region, lore, tags, tagline }) => ({
	spec: 'chara_card_v2',
	spec_version: '2.0',
	data: {
		name, description, personality, scenario, first_mes, mes_example,
		post_history_instructions: `${voice}${HABITS}`,
		system_prompt: '', creator_notes: `${tagline}。${NOTE}`, alternate_greetings: [], tags, creator: 'dsh-fish-soul', character_version: '5',
		extensions: { fish_soul: { anchor, routine, perspective, moods } },
		character_book: {
			entries: [...lore, CITY(region)].map(([keys, content], i) => ({
				keys, content, constant: keys.length === 0, enabled: true, insertion_order: 100 - i, id: i + 1, extensions: {}
			}))
		}
	}
});

const tpl = ({ id, title, tagline, tags, ...rest }) => ({ id, title, tagline, tags, card: card({ ...rest, tags, tagline }) });

