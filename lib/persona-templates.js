/**
 * persona-templates.js —— 内置人格模板（设置页「人格」里一键换上，也可以改一改再用）。
 *
 * 每张都是 chara_card_v2，能直接导出给 SillyTavern 用；fish-soul 自己多读 extensions.fish_soul：
 *  - anchor  每轮一行的「记住你是谁」（≤80 字）
 *  - routine 作息习惯，每天排日程时参考
 *  - perspective 看事情的方式（2～3 条），进静态人格段
 *
 * 写法上的共同点（活人感）：
 *  0. 按气质分，不按职业分：职业、城市、学校都没写死（世界书里「上班 / 上课」那条让她只说忙不忙、遇到什么事，
 *     别编单位名）；想要具体身份，在「她是谁」开头加一句就行。活人感靠的是下面这些，不靠职业；
 *  1. 具体而不完美：住处、宠物、爱好、讨厌的东西，还有一件拖着没做完的事、一点没解决的烦心事；
 *  1b. 看事情的方式（extensions.fish_soul.perspective，借鉴 HDS-Interlude）：2～3 条她自己的价值观，
 *     彼此可以有点矛盾；遇到相关的事才影响她怎么选，不当主题、不说教；
 *  2. 有自己的生活：会忙、会累、会不想聊、会主动讲今天的破事，而不是围着对方转；
 *  3. 有观点、会拒绝、有不懂的：不当客服、不写作业、不列清单；写明她不懂什么，问到就说不懂；
 *  4. 说话方式写清楚：短句、拆成几条发、语气词和标点；口头禅写上但注明「隔很久才冒一次」，
 *     不然模型每条都带；允许省主语、说半句、只回一个「嗯」；也写她在群里是什么样；
 *  5. 示例少而精、场合要散：日常、被夸、被冒犯、聊到不懂的、群里插一句、深夜，每段只演一个特点，
 *     同一个词别在几段里反复出现（Ali:Chat 的经验：放进去什么就学出什么）；
 *  6. 每轮提醒（post_history_instructions）= 她自己的一句 + 共同的分寸（HABITS，参考 MaiBot 预设）；
 *  7. 细节放世界书：聊到才带出来（猫、老家、工作），不聊不占位置，也不会每句都提。
 */

/** 每张卡每轮都带的分寸：不重复自己、群聊一次一个话题、别句句反问、附和要具体、允许不完整 */
export const HABITS = '口头禅隔很久才用一次，别重复上文自己用过的句式和开头，也不用每句都演自己的性格；一次只接一个话题，别句句反问；附和就说具体哪里好，别光说「确实」；可以省主语、说半句，只回个「嗯」也行。';

/** 示例对话：'> ' 开头是对方说的，其余是她说的；一个数组一段 */
const examples = (...blocks) => blocks.map((b) => `<START>\n${b.map((l) => (l.startsWith('> ') ? `{{user}}: ${l.slice(2)}` : `{{char}}: ${l}`)).join('\n')}`).join('\n');

/** 每张卡的作者备注：职业没写死，想要就自己加 */
const NOTE = '职业、城市没写死：想要具体身份，就在「她是谁」开头加一句（比如「在杭州读设计」），再把世界书里「上班 / 上课」那条改成具体的。';

/** 每张卡都带：问到在哪个城市只说个大概（模型会从方言、吃的猜一个具体城市出来） */
const CITY = [['哪个城市', '哪里人', '哪儿人', '在哪住', '住哪', '城市', '在哪个', '定位'], '{{char}} 住在哪个城市没写死：问到只说个大概（南方 / 北方 / 一个小城），或者反问回去，别报具体的城市名、区名和路名，也别从口味、方言去猜一个出来。'];

const card = ({ name, description, personality, scenario, first_mes, mes_example, voice, anchor, routine, perspective, lore, tags, tagline }) => ({
	spec: 'chara_card_v2',
	spec_version: '2.0',
	data: {
		name, description, personality, scenario, first_mes, mes_example,
		post_history_instructions: `${voice}${HABITS}`,
		system_prompt: '', creator_notes: `${tagline}。${NOTE}`, alternate_greetings: [], tags, creator: 'dsh-fish-soul', character_version: '3',
		extensions: { fish_soul: { anchor, routine, perspective } },
		character_book: {
			entries: [...lore, CITY].map(([keys, content], i) => ({
				keys, content, constant: keys.length === 0, enabled: true, insertion_order: 100 - i, id: i + 1, extensions: {}
			}))
		}
	}
});

const tpl = ({ id, title, tagline, tags, ...rest }) => ({ id, title, tagline, tags, card: card({ ...rest, tags, tagline }) });

